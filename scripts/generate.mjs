#!/usr/bin/env node
// Generates source modules that other code imports:
//   packages/core/src/scenes/generated.ts          - the reference scenes as strings
//   packages/generation/src/generated/contract.ts  - the SDK's type contract, one declaration per name
// Run automatically before tests, typechecks and the playground.
import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function writeIfChanged(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  if (existsSync(path) && readFileSync(path, 'utf8') === content) return false;
  writeFileSync(path, content);
  return true;
}

export function generateScenes() {
  const scenesDir = join(root, 'packages/core/scenes');
  const scenes = {};
  for (const id of readdirSync(scenesDir).sort()) {
    const dir = join(scenesDir, id);
    if (!statSync(dir).isDirectory()) continue;
    const read = (name) => readFileSync(join(dir, name), 'utf8');
    scenes[id] = {
      id,
      html: read('scene.html'),
      css: read('scene.css'),
      js: read('scene.js'),
      plan: JSON.parse(read('plan.json')),
    };
  }
  const body =
    '// Generated by scripts/generate.mjs from packages/core/scenes. Do not edit.\n' +
    "import type { ScenePlan } from '../protocol/plan';\n\n" +
    'export const REFERENCE_SCENE_SOURCES: Readonly<Record<string, { readonly id: string; readonly html: string; readonly css: string; readonly js: string; readonly plan: ScenePlan }>> = ' +
    JSON.stringify(scenes, null, 2) +
    ';\n';
  return writeIfChanged(join(root, 'packages/core/src/scenes/generated.ts'), body);
}

/**
 * Splits the SDK's public type contract into its declarations, with their doc
 * comments, so the scene call receives exactly the declarations its plan needs
 * and never a hand-copied description that could drift from the SDK.
 */
export async function generateContract() {
  const { default: ts } = await import('typescript');
  const path = join(root, 'packages/core/src/api/types.ts');
  const text = readFileSync(path, 'utf8');
  const source = ts.createSourceFile(path, text, ts.ScriptTarget.ES2022, true);
  const declarations = {};
  for (const statement of source.statements) {
    if (!ts.isInterfaceDeclaration(statement) && !ts.isTypeAliasDeclaration(statement)) continue;
    // Only the doc comment right above the declaration: the first one also carries the file's header.
    const doc = (ts.getLeadingCommentRanges(text, statement.getFullStart()) ?? [])
      .map((range) => text.slice(range.pos, range.end))
      .filter((comment) => comment.startsWith('/**'))
      .at(-1);
    const body = text.slice(statement.getStart(), statement.getEnd()).replace(/^export /, '');
    declarations[statement.name.text] = doc ? `${doc}\n${body}` : body;
  }
  const body =
    '// Generated by scripts/generate.mjs from packages/core/src/api/types.ts. Do not edit.\n\n' +
    '/** The SDK type contract, by declaration name. */\n' +
    'export const SDK_CONTRACT: Readonly<Record<string, string>> = ' +
    JSON.stringify(declarations, null, 2) +
    ';\n';
  return writeIfChanged(join(root, 'packages/generation/src/generated/contract.ts'), body);
}

export async function generate() {
  generateScenes();
  await generateContract();
  const bundles = join(root, 'scripts/build-sandbox-bundles.mjs');
  if (existsSync(bundles)) {
    const { buildSandboxBundles } = await import(bundles);
    await buildSandboxBundles();
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generate();
}
