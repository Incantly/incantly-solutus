#!/usr/bin/env node
// Builds the two scripts that run inside the sandbox and writes them, with the
// frame script's CSP hash, to packages/core/src/sandbox/generated/bundles.ts:
//   FRAME_SCRIPT  - the renderer and bridge, inlined into the frame's srcdoc
//   WORKER_SCRIPT - the scene runtime and probe, joined to the scene in a blob Worker
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'packages/core/src');
const generated = join(src, 'sandbox/generated');

async function bundle(entry) {
  const result = await build({
    entryPoints: [join(root, entry)],
    bundle: true,
    minify: true,
    format: 'iife',
    platform: 'browser',
    // Older WebKit in iPad web views: keep the syntax conservative.
    target: 'es2020',
    write: false,
    legalComments: 'none',
    // Release hygiene (RM-5): the sandbox never writes to the console.
    drop: ['console', 'debugger'],
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

function writeIfChanged(path, body) {
  mkdirSync(dirname(path), { recursive: true });
  if (!existsSync(path) || readFileSync(path, 'utf8') !== body) writeFileSync(path, body);
}

/** The module paths the base Worker shares with kit scripts (sandbox/kit-shared.ts). */
function sharedModules() {
  const text = readFileSync(join(src, 'sandbox/kit-shared.ts'), 'utf8');
  return new Set([...text.matchAll(/^\s*'([a-z0-9/-]+)':/gm)].map((match) => match[1]));
}

/** Kits are the directories under packages/core/src/kits with an index.ts. */
export function kitNames() {
  const dir = join(src, 'kits');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => /^[a-z0-9]+$/.test(name) && existsSync(join(dir, name, 'index.ts')))
    .sort();
}

/**
 * Leaves the base Worker's shared modules out of a kit script: the kit reads
 * them from the Worker at run time, so classes like handles and errors are the
 * runtime's own. Anything else from outside the kit's directory is refused.
 */
function sharedPlugin(kitDir, shared) {
  return {
    name: 'incantly-kit-shared',
    setup(build) {
      build.onResolve({ filter: /^\.\.?\// }, (args) => {
        const full = resolve(args.resolveDir, args.path).replace(/\.ts$/, '');
        if (full === kitDir || full.startsWith(kitDir + sep)) return undefined;
        const key = relative(src, full).split(sep).join('/');
        if (!shared.has(key)) {
          return { errors: [{ text: `The kit imports ${key}, which the base Worker does not share. Add it to sandbox/kit-shared.ts or move it into the kit.` }] };
        }
        return { path: key, namespace: 'incantly-shared' };
      });
      build.onLoad({ filter: /.*/, namespace: 'incantly-shared' }, (args) => ({
        contents: `module.exports = globalThis.__incShared[${JSON.stringify(args.path)}];`,
        loader: 'js',
      }));
    },
  };
}

/** A kit as a script joined to the Worker after the base runtime; it registers itself for the scene. */
async function bundleKit(name, shared) {
  const kitDir = join(src, 'kits', name);
  const result = await build({
    stdin: {
      contents: "import { kit } from './index';\nconst g = globalThis;\nconst registry = g.__incKits || (g.__incKits = {});\nregistry[kit.name] = kit;\n",
      resolveDir: kitDir,
      sourcefile: `${name}-entry.ts`,
      loader: 'ts',
    },
    bundle: true,
    minify: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    write: false,
    legalComments: 'none',
    drop: ['console', 'debugger'],
    logLevel: 'silent',
    plugins: [sharedPlugin(kitDir, shared)],
  });
  return result.outputFiles[0].text;
}

export async function buildKitScripts() {
  const shared = sharedModules();
  const names = kitNames();
  const sizes = {};
  for (const name of names) {
    const code = await bundleKit(name, shared);
    if (/\beval\(|new Function\(/.test(code)) throw new Error(`The ${name} kit uses eval, which the frame's policy forbids`);
    sizes[name] = code.length;
    writeIfChanged(join(generated, 'kits', `${name}.ts`), '// Generated by scripts/build-sandbox-bundles.mjs. Do not edit.\n' + `export const KIT_SCRIPT = ${JSON.stringify(code)};\n`);
  }
  const loaders = names.map((name) => `  ${name}: () => import('./kits/${name}').then((m) => m.KIT_SCRIPT),\n`).join('');
  writeIfChanged(
    join(generated, 'kit-scripts.ts'),
    '// Generated by scripts/build-sandbox-bundles.mjs. Do not edit.\n' +
      "import type { KitName } from '../../runtime/kits';\n\n" +
      '/** Loads each kit script this build has, only when a scene needs it. */\n' +
      `export const KIT_SCRIPTS: Readonly<Partial<Record<KitName, () => Promise<string>>>> = {\n${loaders}};\n`,
  );
  return sizes;
}

export async function buildSandboxBundles() {
  const frame = await bundle('packages/core/src/sandbox/frame-entry.ts');
  const worker = await bundle('packages/core/src/sandbox/worker-entry.ts');
  // The frame script is inlined into HTML, so it must not be able to end its own element.
  if (/<\/script|<script|<!--/i.test(frame)) {
    throw new Error('The frame bundle contains markup that would break out of its script element');
  }
  for (const [name, code] of [
    ['frame', frame],
    ['worker', worker],
  ]) {
    if (/\beval\(|new Function\(/.test(code)) throw new Error(`The ${name} bundle uses eval, which the frame's policy forbids`);
  }
  const hash = `'sha256-${createHash('sha256').update(frame, 'utf8').digest('base64')}'`;
  const body =
    '// Generated by scripts/build-sandbox-bundles.mjs. Do not edit.\n' +
    `export const FRAME_SCRIPT = ${JSON.stringify(frame)};\n` +
    `export const FRAME_SCRIPT_HASH = ${JSON.stringify(hash)};\n` +
    `export const WORKER_SCRIPT = ${JSON.stringify(worker)};\n`;
  writeIfChanged(join(generated, 'bundles.ts'), body);
  const kits = await buildKitScripts();
  return { frameBytes: frame.length, workerBytes: worker.length, kits };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sizes = await buildSandboxBundles();
  const kits = Object.entries(sizes.kits).map(([name, bytes]) => `, ${name} kit ${(bytes / 1024).toFixed(1)} KB`).join('');
  console.log(`frame ${(sizes.frameBytes / 1024).toFixed(1)} KB, worker ${(sizes.workerBytes / 1024).toFixed(1)} KB${kits}`);
}
