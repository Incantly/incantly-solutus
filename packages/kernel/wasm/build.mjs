/**
 * Builds the physics kernels (design 11.6): compiles `packages/kernel/wasm` to WebAssembly with cargo and writes the bytes
 * as `packages/kernel/src/physics/wasm/kernels-wasm.ts`, which is committed, so the repository and CI need no Rust.
 *
 * Run from the repository root: `npm run build:wasm`. It needs the Rust toolchain (rustup, cargo and the
 * `wasm32-unknown-unknown` target); no crates are used (docs/design/libraries.md). With `--check` it builds and fails
 * when the committed file differs from the build, writing nothing.
 */
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
const manifest = path.join(here, 'Cargo.toml');
const target = path.join(here, 'target');
// the build with SIMD has its own target directory, inside the ignored one
const targetSimd = path.join(target, 'simd');
const wasmName = path.join('wasm32-unknown-unknown', 'release', 'incantly_physics_kernels.wasm');
const outFile = path.join(root, 'packages', 'kernel', 'src', 'physics', 'wasm', 'kernels-wasm.ts');
const out = (s) => process.stdout.write(`${s}\n`);

const cargoBin = path.join(homedir(), '.cargo', 'bin');
const baseEnv = { ...process.env, PATH: `${cargoBin}${path.delimiter}${process.env.PATH ?? ''}` };
// the same bytes on every computer: no flags that change how numbers are worked out
delete baseEnv.RUSTFLAGS;
delete baseEnv.CARGO_ENCODED_RUSTFLAGS;

/** Builds the crate once (`simd`: with the 128-bit SIMD instructions on) and returns the module's bytes. */
function build(simd) {
  const dir = simd ? targetSimd : target;
  const env = { ...baseEnv, CARGO_TARGET_DIR: dir, ...(simd ? { RUSTFLAGS: '-C target-feature=+simd128' } : {}) };
  const run = spawnSync('cargo', ['build', '--release', '--locked', '--target', 'wasm32-unknown-unknown', '--manifest-path', manifest], { env, stdio: 'inherit' });
  if (run.status !== 0) {
    out('cargo build failed (is the Rust toolchain installed, with the wasm32-unknown-unknown target?)');
    process.exit(run.status ?? 1);
  }
  const file = path.join(dir, wasmName);
  if (!existsSync(file)) {
    out(`no ${file}`);
    process.exit(1);
  }
  return readFileSync(file);
}

const bytes = build(false);
const simdBytes = build(true);
const sha = createHash('sha256').update(bytes).digest('hex');
const simdSha = createHash('sha256').update(simdBytes).digest('hex');
// The sources the bytes come from: lib.rs, Cargo.toml and Cargo.lock, in that order. CI has no Rust, so a test hashes the
// three files and compares with this line of the header: it fails when a source changed and this file was not rebuilt.
const sourceHash = createHash('sha256');
for (const f of [path.join(here, 'src', 'lib.rs'), manifest, path.join(here, 'Cargo.lock')]) sourceHash.update(readFileSync(f));
const sourcesSha = sourceHash.digest('hex');
const text = `/**
 * GENERATED by \`npm run build:wasm\` (packages/kernel/wasm/build.mjs) from packages/kernel/wasm/src/lib.rs. Do not edit.
 *
 * The hot loops of the cloth, liquid and smoke solvers as WebAssembly modules (docs/features/physics/design.md 11.6), as
 * base64, so the repository and CI need no Rust toolchain. To rebuild: install Rust (rustup, with the wasm32-unknown-unknown
 * target) and run \`npm run build:wasm\`.
 *
 * Two builds of the same source: the scalar module (the cloth and the 3D liquid, and the grid in space where the engine has
 * no SIMD) and the module built with \`-C target-feature=+simd128\` (the grid in space). Both give the same bits.
 *
 * Size: ${bytes.length} bytes. SHA-256 of the bytes: ${sha}
 * Size with SIMD: ${simdBytes.length} bytes. SHA-256 of the bytes with SIMD: ${simdSha}
 * SHA-256 of the sources (src/lib.rs, Cargo.toml, Cargo.lock, in that order, bytes joined): ${sourcesSha}
 */
export const KERNELS_WASM_BASE64 = '${bytes.toString('base64')}';
export const KERNELS_SIMD_WASM_BASE64 = '${simdBytes.toString('base64')}';
`;
if (process.argv.includes('--check')) {
  const have = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (have !== text) {
    out(`${path.relative(root, outFile)} is not what the Rust source builds to (run npm run build:wasm)`);
    process.exit(1);
  }
  out(`${path.relative(root, outFile)} matches the build (${bytes.length} bytes, sha256 ${sha}; with SIMD ${simdBytes.length} bytes, sha256 ${simdSha})`);
} else {
  writeFileSync(outFile, text);
  out(`wrote ${path.relative(root, outFile)}: ${bytes.length} bytes, sha256 ${sha}; with SIMD ${simdBytes.length} bytes, sha256 ${simdSha}`);
}
